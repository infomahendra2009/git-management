#!/usr/bin/env node
// Database migration helper.
//   node scripts/migrate.mjs baseline        one time: turn the current database into migration "init"
//   node scripts/migrate.mjs new <name>      after editing schema.prisma: write a migration for the change
// New migrations are applied automatically the next time the API starts (prisma migrate deploy).
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('prisma/migrations');
const schema = 'prisma/schema.prisma';
const [cmd, ...rest] = process.argv.slice(2);

const prisma = (args, capture = false) =>
  spawnSync('npx', ['prisma', ...args], { encoding: 'utf8', stdio: capture ? ['inherit', 'pipe', 'inherit'] : 'inherit' });
const existing = () => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((d) => fs.existsSync(path.join(dir, d, 'migration.sql'))) : []);
const lock = () => fs.writeFileSync(path.join(dir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "mysql"\n');
const fail = (m) => { console.error(m); process.exit(1); };

if (cmd === 'baseline') {
  if (existing().length) fail('Migrations already exist. Use "new <name>" for further changes.');
  const r = prisma(['migrate', 'diff', '--from-empty', '--to-schema-datamodel', schema, '--script'], true);
  if (r.status !== 0 || !r.stdout.trim()) fail('Could not generate the baseline SQL.');
  const name = '00000000000000_init';
  fs.mkdirSync(path.join(dir, name), { recursive: true });
  fs.writeFileSync(path.join(dir, name, 'migration.sql'), r.stdout);
  lock();
  // The tables already exist (created by "db push"), so record this migration as applied.
  const done = prisma(['migrate', 'resolve', '--applied', name]);
  if (done.status !== 0) fail('Baseline file written, but marking it applied failed. Run: npx prisma migrate resolve --applied ' + name);
  console.log(`Baseline created in prisma/migrations/${name}. Commit this folder to git.`);
} else if (cmd === 'new') {
  const name = (rest[0] || '').replace(/[^A-Za-z0-9_]+/g, '_');
  if (!name) fail('Usage: npm run migrate:new -- <short_name>');
  if (!existing().length) fail('Run "npm run migrate:baseline" first.');
  // Compare the live database with schema.prisma (no shadow database needed).
  const r = prisma(['migrate', 'diff', '--from-schema-datasource', schema, '--to-schema-datamodel', schema, '--script'], true);
  if (r.status !== 0) fail('Could not compare the database with schema.prisma.');
  if (!r.stdout.trim() || /empty migration/i.test(r.stdout)) { console.log('No schema changes found. Nothing written.'); process.exit(0); }
  const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  const folder = `${stamp}_${name}`;
  fs.mkdirSync(path.join(dir, folder), { recursive: true });
  fs.writeFileSync(path.join(dir, folder, 'migration.sql'), r.stdout);
  console.log(`Wrote prisma/migrations/${folder}/migration.sql. Review it, commit it, then restart the API to apply it.`);
} else {
  fail('Usage: node scripts/migrate.mjs baseline | new <name>');
}
